/// Fixed UI strings for Bingo Online.
///
/// Follows the tier-online convention (`lib/l10n/app_localizations.dart`): one
/// key-value dictionary per [AppLocale], `t()` with an English fallback and
/// `{placeholder}` substitution via [format]. Kept as a separate dictionary so
/// the bingo module can be merged into tier-online later without key clashes.
class BingoLocalizations {
  const BingoLocalizations(this.locale);
  final AppLocale locale;

  static final supportedLocales = InternationalizationConfig.localeProfiles
      .map((profile) => profile.flutterLocale)
      .toList(growable: false);
  static const delegate = _BingoLocalizationsDelegate();

  static BingoLocalizations of(BuildContext context) =>
      Localizations.of<BingoLocalizations>(context, BingoLocalizations) ??
      const BingoLocalizations(AppLocale.ja);

  String t(String key) =>
      (_values[locale] ?? _values[AppLocale.en])![key] ??
      _values[AppLocale.en]![key] ??
      key;

  String format(String key, Map<String, Object> values) {
    var result = t(key);
    for (final entry in values.entries) {
      result = result.replaceAll('{${entry.key}}', '${entry.value}');
    }
    return result;
  }

  String count(String key, int value) => format(key, {'count': value});

  String regionName(String code) => t('region.$code');

  String relativeTime(DateTime? time) {
    if (time == null) return '';
    final difference = DateTime.now().difference(time);
    if (difference.inMinutes < 1) return t('timeJustNow');
    if (difference.inHours < 1) {
      return count('timeMinutes', difference.inMinutes);
    }
    if (difference.inDays < 1) return count('timeHours', difference.inHours);
    return count('timeDays', difference.inDays);
  }

