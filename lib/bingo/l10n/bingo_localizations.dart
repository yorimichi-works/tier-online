class _BingoLocalizationsDelegate
    extends LocalizationsDelegate<BingoLocalizations> {
  const _BingoLocalizationsDelegate();

  @override
  bool isSupported(Locale locale) =>
      AppLocaleParser.fromCode(locale.toLanguageTag()) != null ||
      AppLocaleParser.fromCode(locale.languageCode) != null;

  @override
  Future<BingoLocalizations> load(Locale locale) => SynchronousFuture(
    BingoLocalizations(
      AppLocaleParser.fromCode(locale.toLanguageTag()) ??
          AppLocaleParser.fromCode(locale.languageCode) ??
          AppLocale.en,
    ),
  );

  @override
  bool shouldReload(_BingoLocalizationsDelegate old) => false;
}

extension BingoLocalizationContext on BuildContext {
  BingoLocalizations get bingo => BingoLocalizations.of(this);
}
