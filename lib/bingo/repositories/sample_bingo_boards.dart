class _Template {
  const _Template({
    required this.id,
    required this.size,
    required this.freeCenter,
    required this.titles,
    required this.descriptions,
    required this.tags,
    required this.cells,
  });

  final String id;
  final int size;
  final bool freeCenter;
  final Map<AppLocale, String> titles;
  final Map<AppLocale, String> descriptions;
  final Map<AppLocale, List<String>> tags;
  final Map<AppLocale, List<String>> cells;
}

extension BingoServiceName on AppLocale {
  /// Bingo counterpart of [LocaleProfile.serviceName].
  String get serviceNameForBingo => switch (this) {
    AppLocale.ja => 'ビンゴオンライン',
    AppLocale.ko => '빙고 온라인',
    AppLocale.en => 'Bingo Online',
    AppLocale.zhTw => '賓果線上版',
    AppLocale.ptBr => 'Bingo Online',
  };
}
